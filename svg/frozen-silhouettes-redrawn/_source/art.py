def pt(cx, cy, r, a):              # a in degrees, 0 = up, clockwise
    t = math.radians(a)
    return cx + r*math.sin(t), cy - r*math.cos(t)
def poly(pts, col=K):
    return P('M' + ' L'.join(f'{x:.2f},{y:.2f}' for x, y in pts) + ' Z', col, 0)
def stroke(d, w, col=K, cap='round'):
    return f'<path d="{d}" fill="none" stroke="{col}" stroke-width="{w}" stroke-linecap="{cap}" stroke-linejoin="round"/>'
def seg(p, q, w, col=K, cap='round'):
    return stroke(f'M{p[0]:.2f},{p[1]:.2f} L{q[0]:.2f},{q[1]:.2f}', w, col, cap)
def diamond(cx, cy, a, L0, L1, wd, col=K):
    """kite along direction a: from radius L0 to L1 (from (cx,cy)), max width wd at 40%"""
    m = L0 + 0.4*(L1 - L0)
    p0, p1 = pt(cx, cy, L0, a), pt(cx, cy, L1, a)
    pm = pt(cx, cy, m, a)
    ox, oy = math.cos(math.radians(a))*wd/2, math.sin(math.radians(a))*wd/2
    return poly([p0, (pm[0]+ox, pm[1]+oy), p1, (pm[0]-ox, pm[1]-oy)], col)
def star4(cx, cy, rx, ry=None, waist=0.18, col=K):
    ry = ry or rx; q = waist
    d = (f'M{cx},{cy-ry} Q{cx+rx*q},{cy-ry*q} {cx+rx},{cy} Q{cx+rx*q},{cy+ry*q} {cx},{cy+ry} '
         f'Q{cx-rx*q},{cy+ry*q} {cx-rx},{cy} Q{cx-rx*q},{cy-ry*q} {cx},{cy-ry} Z')
    return P(d, col, 0)
def star8(cx, cy, r, r2=None, col=K):
    r2 = r2 or r*0.55
    pts = []
    for i in range(16):
        rr = r if i % 4 == 0 else (r2 if i % 2 == 0 else r*0.16)
        pts.append(pt(cx, cy, rr, i*22.5))
    return poly(pts, col)
def taper(p0, c1, c2, p1, w0, w1, col=K, n=48):
    """filled stroke along a cubic bezier, width w0 -> w1"""
    def B(t):
        u = 1 - t
        return (u**3*p0[0] + 3*u*u*t*c1[0] + 3*u*t*t*c2[0] + t**3*p1[0],
                u**3*p0[1] + 3*u*u*t*c1[1] + 3*u*t*t*c2[1] + t**3*p1[1])
    L, Rr = [], []
    for i in range(n + 1):
        t = i/n; x, y = B(t); x2, y2 = B(min(t + 1e-3, 1)); x1, y1 = B(max(t - 1e-3, 0))
        dx, dy = x2 - x1, y2 - y1; l = math.hypot(dx, dy) or 1
        w = (w0 + (w1 - w0)*t)/2
        L.append((x - dy/l*w, y + dx/l*w)); Rr.append((x + dy/l*w, y - dx/l*w))
    return poly(L + Rr[::-1], col)
def dots(pts, r=4, col=K): return ''.join(Cc(p[0], p[1], p[2] if len(p) > 2 else r, col, 0) for p in pts)

def flake(cx, cy, r, v=1, col=K, hole=W, rot=0):
    """D6-symmetric snowflake, several designs"""
    o = ''
    for i in range(6):
        a = rot + 60*i
        if v == 1:
            o += seg((cx, cy), pt(cx, cy, r*0.78, a), r*0.07, col)
            o += diamond(cx, cy, a, r*0.70, r, r*0.2, col)
            for t, L, w in ((0.32, 0.30, 0.055), (0.55, 0.24, 0.05)):
                b = pt(cx, cy, r*t, a)
                for s in (-1, 1):
                    e = pt(*b, r*L, a + s*48)
                    o += seg(b, e, r*w, col) + diamond(*b, a + s*48, r*L*0.75, r*L*1.15, r*0.07, col)
        elif v == 2:
            o += seg((cx, cy), pt(cx, cy, r*0.75, a), r*0.08, col)
            o += diamond(cx, cy, a, r*0.68, r, r*0.22, col)
            o += diamond(cx, cy, a + 30, r*0.12, r*0.62, r*0.13, col)
            for t, L in ((0.42, 0.26), (0.62, 0.18)):
                b = pt(cx, cy, r*t, a)
                for s in (-1, 1): o += seg(b, pt(*b, r*L, a + s*45), r*0.055, col)
            o += Cc(*pt(cx, cy, r*0.86, a + 30), r*0.05, col, 0)
        elif v == 3:
            o += seg((cx, cy), pt(cx, cy, r*0.8, a), r*0.065, col)
            o += diamond(cx, cy, a, r*0.74, r, r*0.17, col)
            for t, L in ((0.22, 0.2), (0.38, 0.26), (0.54, 0.22), (0.68, 0.14)):
                b = pt(cx, cy, r*t, a)
                for s in (-1, 1): o += seg(b, pt(*b, r*L, a + s*42), r*0.045, col)
            o += Cc(*pt(cx, cy, r*0.88, a + 30), r*0.055, col, 0)
            o += diamond(cx, cy, a + 30, r*0.1, r*0.36, r*0.1, col)
        elif v == 4:
            o += seg((cx, cy), pt(cx, cy, r*0.8, a), r*0.07, col)
            o += diamond(cx, cy, a, r*0.72, r, r*0.19, col)
            o += seg(pt(cx, cy, r*0.3, a), pt(cx, cy, r*0.3, a + 60), r*0.05, col)
            for t, L in ((0.48, 0.3), (0.66, 0.2)):
                b = pt(cx, cy, r*t, a)
                for s in (-1, 1):
                    e = pt(*b, r*L, a + s*50); o += seg(b, e, r*0.05, col)
                    m = pt(*b, r*L*0.55, a + s*50); o += seg(m, pt(*m, r*L*0.45, a), r*0.04, col)
        elif v == 5:        # small simple flake
            o += seg((cx, cy), pt(cx, cy, r, a), r*0.14, col)
            b = pt(cx, cy, r*0.55, a)
            for s in (-1, 1): o += seg(b, pt(*b, r*0.35, a + s*45), r*0.12, col)
    if v == 1: o += Cc(cx, cy, r*0.15, col, 0) + Cc(cx, cy, r*0.07, hole, 0)
    if v == 2: o += Cc(cx, cy, r*0.12, col, 0) + Cc(cx, cy, r*0.05, hole, 0)
    if v == 3: o += Cc(cx, cy, r*0.1, col, 0)
    if v == 4: o += Cc(cx, cy, r*0.11, col, 0) + Cc(cx, cy, r*0.05, hole, 0)
    if v == 5: o += Cc(cx, cy, r*0.12, col, 0)
    return o

def pine(cx, by, h, w, tiers=5, col=K, trunk=True):
    """pine with drooping tiers"""
    o = R(cx - w*0.05, by - h*0.1, w*0.1, h*0.1, 0, col, 0) if trunk else ''
    top = by - h; base = by - h*0.08
    for i in range(tiers):
        f = (i + 1)/tiers
        yb = top + (base - top)*f; hw = w/2*(0.3 + 0.7*f)
        yt = top + (base - top)*(i/tiers)*0.85
        d = (f'M{cx},{yt - (h*0.06 if i == 0 else 0):.1f} C{cx + hw*0.3:.1f},{yb - (yb-yt)*0.5:.1f} {cx + hw*0.8:.1f},{yb - 4:.1f} {cx + hw:.1f},{yb + 3:.1f} '
             f'Q{cx + hw*0.5:.1f},{yb - 4:.1f} {cx},{yb:.1f} Q{cx - hw*0.5:.1f},{yb - 4:.1f} {cx - hw:.1f},{yb + 3:.1f} '
             f'C{cx - hw*0.8:.1f},{yb - 4:.1f} {cx - hw*0.3:.1f},{yb - (yb-yt)*0.5:.1f} {cx},{yt - (h*0.06 if i == 0 else 0):.1f} Z')
        o += P(d, col, 0)
    return o

def bow(cx, cy, s, col=K, hl=W, tails=True):
    o = ''
    for f in (-1, 1):
        loop = (f'M{cx},{cy} C{cx+f*40*s},{cy-52*s} {cx+f*96*s},{cy-40*s} {cx+f*88*s},{cy+2*s} '
                f'C{cx+f*82*s},{cy+30*s} {cx+f*40*s},{cy+22*s} {cx},{cy} Z')
        o += P(loop, col, 0)
        o += stroke(f'M{cx+f*14*s},{cy-6*s} C{cx+f*40*s},{cy-34*s} {cx+f*76*s},{cy-30*s} {cx+f*74*s},{cy}', 4*s, hl)
        if tails:
            o += P(f'M{cx+f*4*s},{cy+4*s} C{cx+f*16*s},{cy+40*s} {cx+f*30*s},{cy+64*s} {cx+f*52*s},{cy+86*s} '
                   f'L{cx+f*34*s},{cy+82*s} L{cx+f*30*s},{cy+96*s} C{cx+f*14*s},{cy+70*s} {cx+f*4*s},{cy+40*s} {cx-f*4*s},{cy+6*s} Z', col, 0)
    return o + E(cx, cy, 13*s, 11*s, col, 0) + E(cx, cy, 6*s, 5*s, hl, 0)


