"""Frozen-themed one-colour silhouettes on a 400x400 canvas: black = cut, white = cut-out detail."""
import math
from shapes import P, Cc, E, R, snowflake, sparkle, ring

K, W = '#000000', '#ffffff'
ITEMS = {}
def item(name):
    def deco(f): ITEMS[name] = f(); return f
    return deco

def tri(a, b, c, col=K): return P(f'M{a[0]},{a[1]} L{b[0]},{b[1]} L{c[0]},{c[1]} Z', col, 0)
def stroke(d, w, col=K, cap='round'):
    return f'<path d="{d}" fill="none" stroke="{col}" stroke-width="{w}" stroke-linecap="{cap}" stroke-linejoin="round"/>'
def pine(cx, by, h, w, col=K, tiers=4):
    out = R(cx - w*0.07, by - h*0.12, w*0.14, h*0.12, 0, col, 0)
    for i in range(tiers):
        t0 = by - h*0.1 - i*(h*0.85/tiers)
        ww = w*(1 - i*0.2)
        out += tri((cx - ww/2, t0), (cx, t0 - h*0.4), (cx + ww/2, t0), col)
    return out
def castle(cx, by, s, col=K, win=W):
    o = ''
    for x, w, h, sp in ((-75, 30, 120, 45), (45, 30, 120, 45), (-25, 50, 175, 80), (-50, 25, 95, 35), (25, 25, 95, 35)):
        x0, y0 = cx + x*s, by - h*s
        o += R(x0, y0, w*s, h*s, 0, col, 0) + tri((x0 - 3*s, y0 + 1), (x0 + w*s/2, y0 - sp*s), (x0 + w*s + 3*s, y0 + 1), col)
    o += R(cx - 75*s, by - 70*s, 150*s, 70*s, 0, col, 0)
    if win:
        o += P(f'M{cx-12*s},{by} L{cx-12*s},{by-24*s} A{12*s},{12*s} 0 0 1 {cx+12*s},{by-24*s} L{cx+12*s},{by} Z', win, 0)
        for x, y in ((-60, 95), (60, 95), (0, 140), (-37, 70), (37, 70)):
            o += R(cx + x*s - 4*s, by - y*s, 8*s, 13*s, 4*s, win, 0)
    return o


